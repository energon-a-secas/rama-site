export function icon(name, { size = 16, cls = '' } = {}) {
  const body = ICONS[name]
  if (!body) return ''
  return `<svg class="ico${cls ? ` ${cls}` : ''}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`
}

/** Replace each <span data-icon="name"> in the static HTML with its SVG. */
export function fillIcons(root = document) {
  for (const el of root.querySelectorAll('span[data-icon]')) {
    el.outerHTML = icon(el.dataset.icon, { size: Number(el.dataset.size) || 16 })
  }
}
